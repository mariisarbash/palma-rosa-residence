window.getAppLanguage = function getAppLanguage() {
  try {
    const stored = localStorage.getItem(window.APP_LANG_STORAGE_KEY);
    return window.I18N[stored] ? stored : window.APP_DEFAULT_LANG;
  } catch {
    return window.APP_DEFAULT_LANG;
  }
};

window.setAppLanguage = function setAppLanguage(lang) {
  const nextLang = window.I18N[lang] ? lang : window.APP_DEFAULT_LANG;
  try {
    localStorage.setItem(window.APP_LANG_STORAGE_KEY, nextLang);
  } catch {
    /* ignore storage failures */
  }
  window.APP_LANG = nextLang;
};

window.t = function t(key, params) {
  const lang = window.APP_LANG && window.I18N[window.APP_LANG] ? window.APP_LANG : window.APP_DEFAULT_LANG;
  const dict = window.I18N[lang] || window.I18N[window.APP_DEFAULT_LANG];
  const fallback = window.I18N[window.APP_DEFAULT_LANG] || {};
  let value = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : fallback[key];

  if (typeof value === 'function') return value(params || {});
  if (value == null) value = key;

  return String(value).replace(/\{(\w+)\}/g, (_, token) => {
    const replacement = params && Object.prototype.hasOwnProperty.call(params, token) ? params[token] : '';
    return replacement == null ? '' : String(replacement);
  });
};

